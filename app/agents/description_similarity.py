"""Advisory text overlap between two vacancy descriptions (Stage 22, P0-3).

Purpose: notice a vacancy that is the SAME job as one already applied to,
published again under another title or by an intermediary. Measured on the
2026-10-30 catalogue: an applied ALD "Backend Developer" posting was
re-posted verbatim by N.O.C Engineering (twice) and paraphrased by Weber GmbH
and FERCHAU ("Bildverarbeitung & Microservices"); ALD itself renamed another
of its postings. Titles and references differ, so the identifier checks in
`app.services.application_duplicates` cannot see it.

Method -- deterministic, local, no network, no model:

1. Keep only the role-specific part of a posting: sections whose heading
   names tasks or requirements ("Ihre Aufgaben", "Das bringen Sie mit",
   "Your profile" ...). Company introductions and benefit lists are
   employer boilerplate: they make two DIFFERENT jobs of one employer look
   alike (ALD Backend vs. ALD Prozessingenieur) and are dropped.
2. Tokenize (case-folded, umlauts transliterated), drop stop words and
   every stem in `COMMON_JOB_AD_STEMS` -- vocabulary that appears in at
   least 1 % of real job ads (generated by
   `scripts/build_job_ad_common_stems.py`). What remains are the
   distinctive terms ("opc", "opencv", "kamera", "bildve"); a paraphrase
   keeps them even when the sentences are rewritten.
3. Two descriptions are SIMILAR when they share at least `MIN_SHARED`
   distinctive stems AND those cover at least `MIN_OVERLAP` of the smaller
   set (overlap coefficient). Either side with fewer than `MIN_TERMS`
   distinctive stems (empty, too short, no role section) is not compared.

The result is only ever a hint for a human ("same job?"), never proof and
never a block -- see `application_duplicates.SIMILAR_DESCRIPTION`.
"""

import re
from dataclasses import dataclass
from functools import lru_cache

from app.agents.job_ad_common_stems import COMMON_JOB_AD_STEMS

MIN_TERMS = 5
MIN_SHARED = 5
MIN_OVERLAP = 0.6
STEM_LENGTH = 6
MAX_REPORTED_TERMS = 8

_UMLAUTS = str.maketrans({"ä": "ae", "ö": "oe", "ü": "ue", "ß": "ss"})
_WORD = re.compile(r"[a-z][a-z0-9+#]{2,}")
# A heading: a markdown heading line, a bold-only line, or a short line
# ending with a colon.
_HEADING = re.compile(
    r"^[ \t]*(?:#{1,6}[ \t]*(?P<md>[^\n]+)|\*\*(?P<bold>[^\n*]+?)\*\*[ \t]*:?[ \t]*$"
    r"|(?P<colon>[^\n*#•\-][^\n]{1,78}):[ \t]*$)",
    re.MULTILINE,
)
_ROLE_HEADING = re.compile(
    # Candidate-side "bring" phrasings only, modifiers allowed ("Das bringen Sie
    # (idealerweise / dafuer) mit", "Was du mitbringst", "Du bringst ..."). The
    # separable "mit" must END the heading: "So bringen Sie Ihre Karriere mit uns
    # voran" and "Was wir Ihnen bringen" are benefit lists (see _OTHER_HEADING).
    r"beschreibung|aufgabe|taetigkeit|erwarte|verantwort|profil|mitbring|"
    r"bringen\s+sie\b[^\n]{0,30}?\bmit\W*$|bringst\s+du\b[^\n]{0,30}?\bmit\W*$|"
    r"du\s+bringst|sie\s+bringen|anforderung|voraussetz|"
    r"qualifikation|skills|kenntnis|role|responsib|requirement|what you|was du|"
    r"was sie|mission|das machst|dein job|wofuer"
)
_OTHER_HEADING = re.compile(
    r"bieten|vorteil|benefit|freuen|angebot|ueber uns|wir sind|about us|unternehmen|"
    r"why us|warum wir|kontakt|ansprech|bewerb|perks|wir (?:ihnen|dir|euch) bring"
)
_STOP_WORDS = frozenset(
    (
        "und oder der die das den dem des ein eine einer eines einem einen sie ihr ihre ihren "
        "ihrem ihnen wir uns unser unsere unseren du dein deine deinen dir mit fuer von bei auf "
        "aus zur zum als auch sowie im in an zu ist sind wird werden haben hast hat bist sein "
        "idealerweise gerne sehr gute gut erste ersten erfahrung erfahrungen kenntnisse "
        "kenntnissen bereich bereichen umgang sicherer sicheren abgeschlossenes abgeschlossene "
        "studium vergleichbare vergleichbaren qualifikation ausbildung team teams arbeitsweise "
        "selbststaendige strukturierte eigenverantwortliche kommunikation deutsch englisch "
        "deutschkenntnisse englischkenntnisse wort schrift aufgaben profil the and with for you "
        "your our are have experience knowledge good very"
    ).split()
)


def _fold(text: str) -> str:
    # Markdown escapes ("C+\+", "verfahrens\-") would otherwise split words.
    return text.replace(chr(92), "").casefold().translate(_UMLAUTS)


def role_section_text(description: str | None) -> str:
    """The task/requirement sections of a posting. Without any recognizable
    heading the whole text is used; with headings but no task/requirement
    heading, everything except recognized company/benefit sections."""
    text = _fold(description or "")
    headings = [
        (m.start(), (m.group("md") or m.group("bold") or m.group("colon") or "").strip())
        for m in _HEADING.finditer(text)
    ]
    if not headings:
        return text
    sections = []
    for index, (start, heading) in enumerate(headings):
        end = headings[index + 1][0] if index + 1 < len(headings) else len(text)
        sections.append((heading, text[start:end]))
    # "Auf was Sie sich freuen duerfen" names "was Sie" but is a benefit list.
    role = [
        body
        for heading, body in sections
        if _ROLE_HEADING.search(heading) and not _OTHER_HEADING.search(heading)
    ]
    if role:
        return " ".join(body for body in role)
    return " ".join(
        [text[: headings[0][0]]]
        + [body for heading, body in sections if not _OTHER_HEADING.search(heading)]
    )


def text_stems(text: str) -> list[str]:
    """Stop-word-free word stems of already role-filtered text (also used to
    build `COMMON_JOB_AD_STEMS`)."""
    return [word[:STEM_LENGTH] for word in _WORD.findall(_fold(text)) if word not in _STOP_WORDS]


@lru_cache(maxsize=512)
def distinctive_stems(description: str | None) -> frozenset[str]:
    """Cached: the few descriptions of applied jobs are compared against
    every vacancy of a catalogue run (pure function of the text)."""
    return frozenset(
        stem
        for stem in text_stems(role_section_text(description))
        if stem not in COMMON_JOB_AD_STEMS
    )


@dataclass(frozen=True)
class DescriptionSimilarity:
    shared: int
    overlap: float  # shared / the SMALLER set (a repost may add or drop lines)
    terms: tuple[str, ...]
    coverage_of_larger: float = 0.0  # shared / the LARGER set

    @property
    def similar(self) -> bool:
        return self.shared >= MIN_SHARED and self.overlap >= MIN_OVERLAP

    def describe(self) -> str:
        return f"{self.shared} shared distinctive terms, overlap {self.overlap:.2f}: " + ", ".join(
            self.terms
        )


def compare_descriptions(a: str | None, b: str | None) -> DescriptionSimilarity | None:
    """None when either description is too thin to compare (never "similar")."""
    left, right = distinctive_stems(a), distinctive_stems(b)
    if len(left) < MIN_TERMS or len(right) < MIN_TERMS:
        return None
    shared = left & right
    return DescriptionSimilarity(
        shared=len(shared),
        overlap=round(len(shared) / min(len(left), len(right)), 2),
        terms=tuple(sorted(shared)[:MAX_REPORTED_TERMS]),
        coverage_of_larger=round(len(shared) / max(len(left), len(right)), 2),
    )
